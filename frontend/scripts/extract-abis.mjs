// Regenerates src/abi/*.ts from the Foundry build output (run `npm run build` in the repo root first).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const outDir = join(root, "frontend", "src", "abi");
mkdirSync(outDir, { recursive: true });

const contracts = ["PositionManager", "LPVault", "UniV4TwapOracle", "InsuranceReserve", "TraderProxy", "V4SwapRouter"];
for (const name of contracts) {
  const artifact = JSON.parse(readFileSync(join(root, "out", `${name}.sol`, `${name}.json`), "utf8"));
  const exportName = name[0].toLowerCase() + name.slice(1) + "Abi";
  const body = `// Generated by scripts/extract-abis.mjs from out/${name}.sol/${name}.json. Do not edit.\nexport const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
  writeFileSync(join(outDir, `${name}.ts`), body);
  console.log(`wrote src/abi/${name}.ts (${artifact.abi.length} entries)`);
}
