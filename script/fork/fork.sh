#!/usr/bin/env bash
# Local Arc mainnet fork for end-to-end UI testing:  npm run fork
#
#   1. starts anvil forking Arc mainnet (real Uniswap v4 pools, real liquidity)
#   2. installs UsdcForkShim as the USDC implementation (Arc's native-coin precompile does not exist on anvil)
#   3. deploys the protocol with the MVP settings, seeds the LP vault and funds test wallets
#   4. warms up the 10-minute TWAP (fast-forwarding chain time) and switches anvil to 1s interval mining
#   5. writes frontend/.env.development.local and starts the keeper (TWAP recording + liquidations)
#
# Env: ARC_MAINNET_RPC_URL (default https://rpc.mainnet.arc.io), FORK_BLOCK (default latest), FORK_PORT (8545),
#      TEST_WALLET (your own address: gets USDC for trading and native USDC for gas)
# Ctrl-C stops anvil and the keeper. Then run the app:  cd frontend && npm run dev
source "$(dirname "$0")/lib.sh"

UPSTREAM=${ARC_MAINNET_RPC_URL:-https://rpc.mainnet.arc.io}
mkdir -p "$ROOT/.fork" "$ROOT/deployments"

"${CAST[@]}" chain-id -r "$RPC" >/dev/null 2>&1 && die "something is already listening on $RPC (old fork?). Stop it or set FORK_PORT."

DEPLOYER_PK=$(pk 0)
KEEPER_PK=$(pk 1)
TRADER_PK=$(pk 2)
LP_PK=$(pk 3)
KEEPER=$(addr "$KEEPER_PK")
WALLETS="$(addr "$TRADER_PK"),$(addr "$LP_PK")${TEST_WALLET:+,$TEST_WALLET}"

echo "==> Starting anvil (fork of $UPSTREAM${FORK_BLOCK:+ @ $FORK_BLOCK})"
"${ANVIL[@]}" --fork-url "$UPSTREAM" ${FORK_BLOCK:+--fork-block-number "$FORK_BLOCK"} --port "$PORT" \
  >"$ROOT/.fork/anvil.log" 2>&1 &
ANVIL_PID=$!
KEEPER_PID=
cleanup() {
  [[ -n "$KEEPER_PID" ]] && kill "$KEEPER_PID" 2>/dev/null || true
  kill "$ANVIL_PID" 2>/dev/null || true
}
trap cleanup EXIT
for _ in $(seq 1 120); do
  "${CAST[@]}" chain-id -r "$RPC" >/dev/null 2>&1 && break
  kill -0 "$ANVIL_PID" 2>/dev/null || die "anvil exited; see .fork/anvil.log"
  sleep 0.5
done
[[ $("${CAST[@]}" chain-id -r "$RPC") == 5042 ]] || die "fork is not Arc mainnet (chain 5042)"

echo "==> Installing the USDC fork shim"
SHIM=0x000000000000000000000000000000000000F0C5
CODE=$("${FORGE[@]}" inspect UsdcForkShim deployedBytecode)
"${CAST[@]}" rpc -r "$RPC" anvil_setCode "$SHIM" "$CODE" >/dev/null
IMPL_SLOT=0x7050c9e0f4ca769c69bd3a8ef740bc37934f8e2c036e5a723fd8ee048ed3f8c3
"${CAST[@]}" rpc -r "$RPC" anvil_setStorageAt "$USDC" "$IMPL_SLOT" "$("${CAST[@]}" abi-encode "f(address)" "$SHIM")" >/dev/null
if [[ -n "${TEST_WALLET:-}" ]]; then
  "${CAST[@]}" rpc -r "$RPC" anvil_setBalance "$TEST_WALLET" 0x56BC75E2D63100000 >/dev/null # 100 native USDC for gas
fi

echo "==> Deploying the protocol"
KEEPER=$KEEPER TEST_WALLETS=$WALLETS "${FORGE[@]}" script script/fork/ForkCtl.s.sol --sig 'deploy()' \
  --rpc-url "$RPC" --broadcast --private-key "$DEPLOYER_PK" --slow >"$ROOT/.fork/deploy.log" 2>&1 ||
  { tail -40 "$ROOT/.fork/deploy.log"; die "deployment failed (full log: .fork/deploy.log)"; }

echo "==> Warming up the 10-minute TWAP (fast-forwarding chain time)"
record_twap
warp 610
"${CAST[@]}" rpc -r "$RPC" evm_setIntervalMining 1 >/dev/null # from now on, blocks every second

ENV_FILE="$ROOT/frontend/.env.development.local"
MARK="# generated by npm run fork"
if [[ -f "$ENV_FILE" ]] && ! head -1 "$ENV_FILE" | grep -q "$MARK"; then
  ENV_FILE="$ROOT/frontend/.env.fork"
  echo "    frontend/.env.development.local exists and was not generated by this script; writing $ENV_FILE instead"
fi
cat >"$ENV_FILE" <<EOF
$MARK — local Arc mainnet fork; delete this file to point the app back at mainnet
NEXT_PUBLIC_NETWORK=fork
NEXT_PUBLIC_RPC_URL=$RPC
NEXT_PUBLIC_POSITION_MANAGER=$(json positionManager)
NEXT_PUBLIC_LP_VAULT=$(json lpVault)
NEXT_PUBLIC_ORACLE=$(json oracle)
NEXT_PUBLIC_INSURANCE=$(json insurance)
EOF

if [[ -d "$ROOT/frontend/node_modules" ]]; then
  echo "==> Starting the keeper (log: .fork/keeper.log)"
  (
    cd "$ROOT/frontend"
    set -a
    # shellcheck disable=SC1090
    source "$ENV_FILE"
    set +a
    KEEPER_PRIVATE_KEY=$KEEPER_PK exec npx tsx scripts/keeper.ts
  ) >"$ROOT/.fork/keeper.log" 2>&1 &
  KEEPER_PID=$!
else
  echo "    frontend/node_modules missing: run 'cd frontend && npm install', then start the keeper yourself:"
  echo "    KEEPER_PRIVATE_KEY=$KEEPER_PK npm run keeper"
fi

cat <<EOF

Arc mainnet fork is ready on $RPC (chain 5042)

  PositionManager   $(json positionManager)
  LPVault           $(json lpVault)
  UniV4TwapOracle   $(json oracle)
  V4SwapRouter      $(json router)

  Test wallets (anvil keys, each holds ~10,000 USDC plus 1,000 minted; never use on a real chain):
    trader  $(addr "$TRADER_PK")  key $TRADER_PK
    LP      $(addr "$LP_PK")  key $LP_PK
${TEST_WALLET:+    yours   $TEST_WALLET  (1,000 USDC + 100 native USDC for gas)
}
  Wallet network: RPC $RPC, chain ID 5042, currency USDC.

  Next:   cd frontend && npm run dev          (open http://localhost:3000/app/trade)
  Move a pool:   npm run fork:move -- ETH -8   (ETH -8%; BTC +5 etc.)
  Fast-forward:  npm run fork:warp -- 600      (TWAP follows; the keeper then liquidates / triggers)

Ctrl-C stops the fork and the keeper.
EOF

wait "$ANVIL_PID"
